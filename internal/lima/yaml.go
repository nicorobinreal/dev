// Package lima wraps limactl and generates the Lima instance config dev uses
// for every project VM.
package lima

import (
	"bytes"
	"fmt"
	"regexp"
	"strconv"
	"text/template"
)

// Pinned Ubuntu LTS cloud image. These are the values from Lima's
// templates/_images/ubuntu-lts.yaml (Lima 2.3.0), cross-checked against
// https://cloud-images.ubuntu.com/releases/resolute/release-20261016/SHA256SUMS.
//
// Bumping the image is a deliberate change: update these constants (dated
// release directory, never "current"/"release") and regenerate the golden
// file. A new image only affects VMs created afterwards; existing VMs are
// brought forward by adding a new provisioning step (e.g. an apt full-upgrade
// or release-upgrade step) in internal/provision, which `dev upgrade` runs.
const (
	ImageRelease  = "26.04"
	ImageCodename = "resolute"
	ImageSerial   = "20261016"

	ImageAArch64URL    = "https://cloud-images.ubuntu.com/releases/resolute/release-20261016/ubuntu-26.04-server-cloudimg-arm64.img"
	ImageAArch64Digest = "sha256:8eb876c2ccc4b6ff89e4a65d511815923b285e04503ba465809bf587f763da24"
	ImageX8664URL      = "https://cloud-images.ubuntu.com/releases/resolute/release-20261016/ubuntu-26.04-server-cloudimg-amd64.img"
	ImageX8664Digest   = "sha256:5645d0318ad21f643ebb1ac4567514620e9893380b07b0201fda163baa5b7eb5"
)

// Spec holds the per-VM settings that end up in the generated Lima config.
type Spec struct {
	Name   string // Lima instance name (only used in the header comment)
	CPUs   int
	Memory string // e.g. "8GiB"
	Disk   string // e.g. "60GiB"
}

// sizeRE accepts the size forms Lima understands: "8", "8G", "8GiB", "1.5GiB".
var sizeRE = regexp.MustCompile(`^[0-9]+(\.[0-9]+)?[A-Za-z]{0,3}$`)

// Validate checks the spec before it is rendered.
func (s Spec) Validate() error {
	if s.CPUs <= 0 {
		return fmt.Errorf("lima: cpus must be positive, got %d", s.CPUs)
	}
	if !sizeRE.MatchString(s.Memory) {
		return fmt.Errorf("lima: invalid memory size %q (e.g. 8GiB)", s.Memory)
	}
	if !sizeRE.MatchString(s.Disk) {
		return fmt.Errorf("lima: invalid disk size %q (e.g. 60GiB)", s.Disk)
	}
	return nil
}

var yamlTmpl = template.Must(template.New("lima").Funcs(template.FuncMap{
	"q": strconv.Quote, // JSON-style double quotes are valid YAML scalars
}).Parse(`# Generated by dev for instance {{q .Spec.Name}}. Do not edit; dev regenerates it.
minimumLimaVersion: "2.0.0"
vmType: vz
images:
- location: {{q .ARMURL}}
  arch: aarch64
  digest: {{q .ARMDigest}}
- location: {{q .X86URL}}
  arch: x86_64
  digest: {{q .X86Digest}}
cpus: {{.Spec.CPUs}}
memory: {{q .Spec.Memory}}
disk: {{q .Spec.Disk}}
# No Mac folders are shared into the VM.
mounts: []
mountType: virtiofs
# dev installs Docker Engine itself; skip Lima's containerd/nerdctl.
containerd:
  system: false
  user: false
vmOpts:
  vz:
    rosetta:
      enabled: true
      binfmt: true
# No automatic port forwarding to the Mac: access goes through Tailscale.
# Rules match in order; a 0.0.0.0 guestIP with guestIPMustBeZero=false matches
# any bound address. The explicit loopback/IPv6 rules are belt and braces.
portForwards:
- guestIP: "0.0.0.0"
  guestIPMustBeZero: false
  proto: any
  ignore: true
- guestIP: "127.0.0.1"
  proto: any
  ignore: true
- guestIP: "::"
  guestIPMustBeZero: false
  proto: any
  ignore: true
# Same as Lima's ubuntu-lts template: don't block boot on the NIC rename
# (LP: #2136392).
param:
  internal_netplanOptional: "true"
`))

// GenerateYAML renders the Lima config for a project VM.
func GenerateYAML(s Spec) ([]byte, error) {
	if err := s.Validate(); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	err := yamlTmpl.Execute(&buf, struct {
		Spec                                 Spec
		ARMURL, ARMDigest, X86URL, X86Digest string
	}{s, ImageAArch64URL, ImageAArch64Digest, ImageX8664URL, ImageX8664Digest})
	if err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
